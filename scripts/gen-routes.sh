#!/bin/sh
# Generate Traefik's dynamic route table from the live manifest + domain.
# Fixed infra routes (hub/grader/listener/store) plus one per active `web = true` challenge,
# each Host(<name>.<domain>) -> the container's docker-network name. Run by `just up`.
#
# Usage: scripts/gen-routes.sh [domain]     (default: $DOMAIN or ctf.test)
set -eu

root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
domain=${1:-${DOMAIN:-ctf.test}}
out="$root/infra/traefik/dynamic/routes.yml"

router() {  # name  host  service
  printf '    %s:\n      rule: "Host(`%s.%s`)"\n      entryPoints: [websecure]\n      tls: {}\n      service: %s\n' "$1" "$2" "$domain" "$3"
}
service() { # name  container  port
  printf '    %s:\n      loadBalancer:\n        servers:\n          - url: "http://%s:%s"\n' "$1" "$2" "$3"
}

{
  echo "# generated by scripts/gen-routes.sh — do not edit by hand"
  echo "http:"
  echo "  routers:"
  router hub      hub      hub
  router grader   grader   grader
  router listener listener listener
  router store    store    store
  for d in "$root"/active-challenges/*/; do
    id=$(basename "$d")
    grep -q '^web' "$d/meta.toml" 2>/dev/null || continue
    router "$id" "$id" "$id"
  done
  echo "  services:"
  service hub      vuln-services-web       8000
  service grader   grader                  80
  service listener vuln-services-listener  80
  service store    cors                    80
  for d in "$root"/active-challenges/*/; do
    id=$(basename "$d")
    grep -q '^web' "$d/meta.toml" 2>/dev/null || continue
    service "$id" "$id" 80
  done
} > "$out"

echo "gen-routes: wrote $out for *.$domain"
